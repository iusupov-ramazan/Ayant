package kg.ayant.app.core

/**
 * Флаги первого релиза: что скрыто из интерфейса, но остаётся в коде.
 * Mirrors `SAN/ReleaseFlags.swift` — значения должны совпадать 1:1, иначе
 * Android показывает поверхности, которые iOS сознательно прячет.
 *
 * Каждый флаг — один переключатель для целой поверхности. Выключено то, что
 * не подкреплено бэкендом или оплатой и лишь путало бы пользователя в первой
 * версии. Включать по одному, когда соответствующая часть готова.
 */
object ReleaseFlags {
    /** Вкладка «Поиск» (карта + список). Скрыта: экран карты не прошёл тестирование к релизу. */
    const val SEARCH_TAB = false

    /** Глобальный кошелёк бонусов: капсула «БОНУСЫ», игры, каталог наград, подарки. ВКЛЮЧЁН. */
    const val GLOBAL_BONUS_WALLET = true

    /** Реферальная программа в профиле. ВКЛЮЧЕНА вместе с глобальным кошельком. */
    const val REFERRALS = true

    /** «Продвижение» у хоста: буст и push-кампании. Оплата не подключена — скрыто. */
    const val PROMOTE = false

    /** Кнопка «Добавить в Google Wallet» на карте лояльности (iOS: Apple Wallet). Пасс не подписывается — скрыто. */
    const val WALLET_PASS = false
}
