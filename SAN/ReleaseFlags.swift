import Foundation

/// Флаги первого релиза: что скрыто из интерфейса, но остаётся в коде.
///
/// Каждый флаг — один переключатель для целой поверхности. Выключено то, что
/// не подкреплено бэкендом или оплатой и лишь путало бы пользователя в первой
/// версии. Включать по одному, когда соответствующая часть готова:
/// глобальный кошелёк — когда награды и подарки будут записываться в
/// Firestore; продвижение — когда появится оплата; Apple Wallet — когда
/// настроен pass type ID; поиск — когда экран карты пройдёт тестирование.
enum ReleaseFlags {
    /// Вкладка «Поиск» (карта + список). Скрыта: большой экран, не прошёл
    /// тестирование к релизу. Экраны деталей открывают маршрут во внешних картах.
    static let searchTab = false

    /// Глобальный кошелёк бонусов: капсула «БОНУСЫ», игры (Змейка и Тетрис),
    /// каталог наград, подарки.
    ///
    /// ВКЛЮЧЁН. Что работает полностью: начисление за игры, баланс, подарки,
    /// список купонов. Чего НЕ хватает: награды из каталога выдают купон без
    /// заведения, а `scanCoupon` требует совпадения `coupon.venueID` с
    /// заведением сканера и отвечает `wrong_venue`. То есть «Бесплатный кофе
    /// у партнёра» гость получит, но сотрудник его не погасит, пока у награды
    /// не появится заведение-партнёр. См. `CouponStore.redeem`.
    static let globalBonusWallet = true

    /// Реферальная программа в профиле.
    ///
    /// ВКЛЮЧЕНА вместе с глобальным кошельком: бонусы теперь есть на что
    /// тратить — у наград появилось заведение-партнёр. Начисление делает
    /// Cloud Function `rewardReferral`, клиент забирает его `claimBonusGrants`.
    static let referrals = true

    /// «Продвижение» у хоста: буст и push-кампании. Работает по-настоящему,
    /// но оплата не подключена, а цены в интерфейсе расходятся с расчётом.
    static let promote = false

    /// Импорт постов из Instagram в акции (экран «Посты из Instagram» в
    /// кабинете хоста).
    ///
    /// В DEBUG включён, в релизной сборке — нет, и это не временная заглушка.
    /// Пока приложение Meta не переведено в Live, scope
    /// `instagram_business_basic` действует только для аккаунтов с ролью в
    /// приложении: разработчик подключается и видит свои настоящие посты, а у
    /// обычного заведения та же кнопка закончилась бы ошибкой входа. Разделение
    /// по сборке снимает выбор между «нельзя проверить» и «уедет в App Store
    /// раньше времени». После одобрения в Meta — заменить на `true`.
    #if DEBUG
    static let instagramImport = true
    #else
    static let instagramImport = false
    #endif

    /// Кнопка «Добавить в Apple Wallet» на карте лояльности. Pass type ID на
    /// сервере ещё шаблонный, подпись пасса не пройдёт.
    static let appleWallet = false
}
