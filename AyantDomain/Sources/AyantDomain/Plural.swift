import Foundation

/// Русский счёт: «1 минута», «2 минуты», «5 минут».
///
/// Живёт в домене, потому что это правило языка, а не оформление: его одинаково
/// нужно знать всем экранам обеих платформ. Собственная реализация вместо
/// каталога строк — так же, как это уже сделано в счётчике бонусов: правило
/// короткое, а держать его видимым дешевле, чем искать по `.xcstrings`.
public enum Plural {

    /// - Parameters:
    ///   - one: форма для 1, 21, 31… («минута»)
    ///   - few: форма для 2…4, 22…24… («минуты»)
    ///   - many: форма для 0, 5…20, 25…30… («минут»)
    public static func ru(_ count: Int, _ one: String, _ few: String, _ many: String) -> String {
        let n = abs(count)
        // 11…14 — исключение: «одиннадцать минут», а не «минута», хотя
        // последняя цифра единица.
        if (11...14).contains(n % 100) { return many }
        switch n % 10 {
        case 1: return one
        case 2...4: return few
        default: return many
        }
    }
}
